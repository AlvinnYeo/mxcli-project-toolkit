#!/usr/bin/env python3
"""Generate CUT STUB MDL for the names mx check reports missing (CE1613) — signatures from the 10.24 source."""
import re, subprocess, sys
M="<lab>/mxcli"; SRC="<lab>/web-assets/mono/fsm.mpr"
log=open(sys.argv[1]).read()
need={}
for kind,name in re.findall(r"\"The selected ([a-z ]+) '([^']+)'", log):
    if kind in ("attribute","placeholder","page parameter","parameter"): 
        name=".".join(name.split(".")[:2])
        kind={"attribute":"entity","placeholder":"layout","page parameter":"page","parameter":"microflow"}[kind]
    need.setdefault(kind,set()).add(name)
def desc(kind,name):
    out=subprocess.run([M,"-p",SRC,"-c",f"describe {kind} {name}"],capture_output=True,text=True).stdout
    return "\n".join(l for l in out.splitlines() if not l.startswith("WARNING") and l.strip()!="mdl 1;")
for x in sys.argv[2:]: need.setdefault("entity",set()).add(x)  # second-order: entities only a stub signature names
mods=sorted({n.split(".")[0] for s in need.values() for n in s} - {"Administration"})
o=["mdl 1;","-- CUT STUBS generated by gen-stubs.py from the 10.24 source: signatures verbatim, no behaviour"]
for m in mods: o.append(f"create module {m};")
enums=set()
ents=sorted(need.get("entity",()))
blks={}
for e in ents:
    d=desc("entity",e)
    blks[e]=d[d.index("create or modify"):]
done=set()
def order(e):
    if e in done: return []
    done.add(e); sup=re.search(r"extends ([\w.]+)",blks[e].split("(")[0])
    return (order(sup.group(1)) if sup and sup.group(1) in blks else [])+[e]
seq=[x for e in ents for x in order(e)]
for e in seq:
    blk=blks[e]
    blk=blk[:re.search(r"\n\)",blk).end()]+";"
    blk=re.sub(r"^\s*/\*\*.*?\*/\s*\n","",blk,flags=re.M|re.S)
    blk=re.sub(r"^@.*\n","",blk,flags=re.M)
    enums|=set(re.findall(r"Enumeration\(([\w.]+)\)",blk))
    o.append(f"-- CUT STUB entity {e}\n"+blk)
for en in sorted(enums):
    d=desc("enumeration",en); o.insert(len(mods)+2, f"-- enum copied verbatim\n"+d.strip())
for a in sorted(need.get("association",())):
    if a.startswith("Administration."):  # FSM-modified marketplace module; add to the starter's copy
        pass
    d=desc("association",a); o.append(f"-- CUT STUB association {a}\n"+d.strip())
for mf in sorted(need.get("microflow",())):
    d=desc("microflow",mf)
    head=d[d.index("create or modify"):d.index("\nbegin")]
    head=re.sub(r"^\s*@.*\n","",head,flags=re.M)
    head=re.sub(r"^(folder|export level).*\n?","",head,flags=re.M)
    ret=re.search(r"^returns\s+(.+)$",head,re.M)
    body="  return empty;" if ret and ret.group(1).strip().lower()!="boolean" else ("  return false;" if ret else "  return;")
    o.append(f"-- CUT STUB microflow {mf}: signature only\n{head.rstrip()}\nbegin\n{body}\nend;")
for p in sorted(need.get("page",())):
    d=desc("page",p)
    params=re.search(r"Params: \((.*)\)\n",d).group(1)
    o.append(f"-- CUT STUB page {p}: parameter only, no content\ncreate or modify page {p} (\n  Title: 'CUT STUB {p.split('.')[1]}',\n  Layout: FSM_Specific.LeftMenuLayout,\n  Params: ({params})\n) {{\n  dynamictext stubText (Content: 'CUT STUB: served by the FSM monolith')\n}};")
print("\n\n".join(o))
print("-- needed:",{k:len(v) for k,v in need.items()},file=sys.stderr)
